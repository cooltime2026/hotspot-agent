def main():
    out = []
    for (d, h, v), (img, tmax, memo) in CHT.items():
        r = chantemp.read(str(ROOT / f"images/{img}.png"), tmax); s = chantemp.summary(r)
        row = dict(design=d, hotspot=h, inlet_v_mps=v, img=img, Tmax_C=tmax, memo=memo,
                   fluid_max_C=round(s["fluid_max_C"], 1), fluid_mean_C=round(s["fluid_mean_C"], 1),
                   fin_max_C=round(s["fin_max_C"], 1), hottest_channel=s["hottest_channel"], hottest_y_mm=round(s["hottest_y_mm"], 1),
                   check_fluid_below_fin=round(s["fluid_below_fin_ratio"], 2), check_inversion=round(s["inversion_ratio"], 3), band_C=round(s["band_C"], 1),
                   reliable=s["inversion_ratio"] <= 0.02, boil_risk=s["fluid_max_C"] >= 100)
        row.update({f"ch{j}_mean": round(float(np.nanmean(r["fluid"][j])), 1) for j in range(22)})
        row.update({f"ch{j}_max": round(float(np.nanmax(r["fluid"][j])), 1) for j in range(22)})
        out.append(row)
        print(f"{d} {h} v={v} img {img}: 물 최고 {row['fluid_max_C']} ℃ (채널 {row['hottest_channel']}), 평균 {row['fluid_mean_C']} ℃, "
              f"역전 {row['check_inversion']*100:.1f}% {'' if row['reliable'] else '← 위치 의심'} {'★끓음 위험' if row['boil_risk'] else ''}")
    p = ROOT / "data/ml/channel_temps.csv"
    with open(p, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(out[0])); w.writeheader(); w.writerows(out)
    print("저장:", p.relative_to(ROOT), len(out), "행")


if __name__ == "__main__":
    main()
