# 화면 위 = 1행, 화면 왼쪽 = 1열 (rot180_flip = 항등). 사진 570 축 표시(BOTTOM 뷰, y 아래)와 일치.
FIXED_ORIENT = {**{f"A{i}": (2, True) for i in range(1, 9)}, **{f"B{i}": (2, True) for i in range(1, 9)}, "M0": (2, True), "M1": (2, True), "M3": (2, True), "M4": (2, True)}


def transforms():
    for k in range(4):
        for f in (False, True):
            yield (k, f), (lambda a, k=k, f=f: np.rot90(a[:, ::-1] if f else a, k))


def main():
    runs = {(r["design"], "+".join(parse_cells(r["heat"])), float(r["inlet_velocity_m_s"])): r
            for r in csv.DictReader(open(ROOT / "data/direct_runs.csv", encoding="utf-8"))}
    ref = tempmap.read(str(ROOT / "images/331.png"), 131.8)["lut"]
    out = []
    for key, img in BOTTOM.items():
        d, h, v = key; r = runs.get(key)
        if r is None:
            print("Run 없음:", key); continue
        tmax = float(r["Tmax_bottom_C"])
        res = tempmap.read(str(ROOT / f"images/{img}.png"), tmax, ref_lut=ref)
        hot = [(int(c.split("_")[0]) - 1, int(c.split("_")[1]) - 1) for c in h.split("+")]
        best = []
        for name, T in transforms():
            C = T(res["mean"])[::-1, :]          # 행 0 = r 1 (y 아래)
            best.append((np.mean([C[i, j] for i, j in hot]), name, C, T(res["max"])[::-1, :]))
        best.sort(key=lambda b: -b[0])
        if d in FIXED_ORIENT:                    # 카메라 방향이 확인된 형상: 고정 방향 사용(대칭 핫스팟이면 '최적 방향'이 임의로 바뀌므로)
            fixed = [b for b in best if b[1] == FIXED_ORIENT[d]][0]
            best = [fixed] + [b for b in best if b is not fixed]
        sc, name, C, M = best[0]
        margin = sc - best[1][0]
        row = dict(design=d, hotspot=h, inlet_v_mps=v, img=img, Tmax_C=tmax, orient=f"rot{name[0]*90}{'_flip' if name[1] else ''}",
                   orient_margin_C=round(margin, 1))
        row.update({f"Tmean_{c}": round(C.reshape(-1)[i], 1) for i, c in enumerate(CELL_NAMES)})
        row.update({f"Tcellmax_{c}": round(M.reshape(-1)[i], 1) for i, c in enumerate(CELL_NAMES)})
        out.append(row)
        print(f"{d} {h} v={v} img {img}: 방향 {row['orient']} (차이 {margin:.1f} ℃), 핫스팟 칸 평균 {sc:.1f}, 판 평균 {np.nanmean(C):.1f} ℃")
    with open(ROOT / "data/ml/cell_temps.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(out[0])); w.writeheader(); w.writerows(out)
    print("저장: data/ml/cell_temps.csv", len(out), "행")


if __name__ == "__main__":
    main()
